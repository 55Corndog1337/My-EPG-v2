import assert from 'node:assert/strict';
import {buildNFL} from './nfl-generator.mjs';
const game={channel:'NFL Game 01',xtream_stream_id:'79450',source:'epg37',source_channel_id:'117.NFL'};
const team={channel:'NFL Teams - BILLS',xtream_stream_id:'79561',source:'epg37',source_channel_id:'BuffaloBills.nfl12'};
const replay={channel:'NFL Replay 01',xtream_stream_id:'1329645',source:'static',programme_title:'NFL Replay 01',programme_description:'NFL Replay'};
const event={verified:true,away:'Buffalo Bills',home:'Minnesota Vikings',kickoff:'2026-11-10T01:15:00Z',source_channel_id:'117.NFL',team_source_ids:['BuffaloBills.nfl12']};
const xml=buildNFL([game,team,replay],[event],'2026-11-09');
assert.match(xml,/Upcoming: Buffalo Bills @ Minnesota Vikings/);
assert.match(xml,/Buffalo Bills @ Minnesota Vikings \(Nov 9, 8:15 PM EST\)/);
assert.match(xml,/20261109201500 -0500/);
assert.match(xml,/20261109231500 -0500/);
assert.match(xml,/NFL Replay 01/);
assert.equal((xml.match(/channel="V4.NFL.1329645"/g)||[]).length,1);
assert.match(buildNFL([game],[],'2026-11-09'),/No Game Scheduled/);
assert.match(buildNFL([game],[{...event,verified:false}],'2026-11-09'),/No Game Scheduled/);
assert.match(buildNFL([team],[{...event,kickoff:'2026-11-08T18:00:00Z'}],'2026-11-09'),/Event has Concluded/);
const summer=buildNFL([replay],[],'2026-07-01');
assert.match(summer,/20260701000000 -0400/);
assert.throws(()=>buildNFL([game,game],[],'2026-11-09'),/Duplicate StreamID/);
console.log('NFL V4 generator tests passed');
